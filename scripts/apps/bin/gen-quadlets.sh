#!/bin/sh
# gen-quadlets.sh - generate rootless Quadlet units from apps/<host>/*/compose.yaml
# and link the host stack into the user Quadlet search path.
#
# Design notes:
#   - podman-compose expands `include:` and the app-local .env before podlet
#     runs, so each app keeps its own environment file.
#   - Units are generated next to each compose file because Quadlet resolves
#     relative Volume=/EnvironmentFile= paths against the unit's real directory.
#   - The search path gets one directory symlink to apps/<host>. Quadlet
#     recursively finds every app below it and ./config, ./data, ... stay valid.
#   - Every generated file carries a marker comment. The marker is how the
#     script recognises its own output, so it can overwrite and prune stale
#     units without touching files written by hand.
set -eu

SCRIPT_DIR=$(CDPATH='' cd -P -- "$(dirname -- "$0")" && pwd -P)
REPO_ROOT=$(CDPATH='' cd -P -- "$SCRIPT_DIR/../../.." && pwd -P)

MARKER_PREFIX="# Generated by gen-quadlets.sh"

APPS_ROOT=${APPS_ROOT:-$REPO_ROOT/apps}
QUADLET_DIR=${XDG_CONFIG_HOME:-$HOME/.config}/containers/systemd

HOST=
DRY_RUN=0
RELOAD=1
CLEAN=0
QUIET=0
SKIP_APPS=" "
TMP_ROOT=
SEEN_FILE=

# abspath DIR - make DIR absolute and collapse . and .. without requiring it
# to exist. This replaces realpath -m.
abspath() {
    _ap_path=$1
    case $_ap_path in
    '~') _ap_path=$HOME ;;
    \~/*) _ap_path=$HOME/${_ap_path#\~/} ;;
    esac
    case $_ap_path in
    /*) ;;
    *) _ap_path=$PWD/$_ap_path ;;
    esac

    _ap_out=
    _ap_rest=$_ap_path
    while [ -n "$_ap_rest" ]; do
        _ap_part=${_ap_rest%%/*}
        case $_ap_rest in
        */*) _ap_rest=${_ap_rest#*/} ;;
        *) _ap_rest= ;;
        esac
        case $_ap_part in
        '' | .) ;;
        ..) _ap_out=${_ap_out%/*} ;;
        *) _ap_out=$_ap_out/$_ap_part ;;
        esac
    done
    printf '%s\n' "${_ap_out:-/}"
}

usage() {
    cat <<'EOF'
Usage: gen-quadlets.sh [OPTIONS] [HOST]

Generate rootless Quadlet units from apps/<host>/<app>/compose.yaml and link
the host stack into the Quadlet search path.

Arguments:
  HOST                 Host stack under apps/ (default: hostname -s)

Options:
  -a, --apps-root DIR  apps/ root (default: <repo>/apps)
  -Q, --quadlet-dir DIR
                       Rootless Quadlet directory
                       (default: $XDG_CONFIG_HOME/containers/systemd)
  -n, --dry-run        Print planned actions, write nothing
  -q, --quiet          Only print warnings and errors
      --no-reload      Do not run systemctl --user daemon-reload
      --skip APP       Skip an app directory (repeatable), e.g. a stack that
                       uses compose features podlet cannot convert yet
      --clean          Remove generated units and links pointing into apps/
  -h, --help           Show this help

The rootless search paths, per podman-systemd.unit(5), are:
  $XDG_RUNTIME_DIR/containers/systemd/
  $XDG_CONFIG_HOME/containers/systemd/   (default; ~/.config/containers/systemd)
  /etc/containers/systemd/users/${UID}/
  /usr/share/containers/systemd/users/${UID}/

Quadlet follows symbolic links inside these paths. The script links the host
directory, not individual files, because relative bind sources are resolved
against the unit's real directory.

Requires: podman-compose, podlet.
EOF
}

log() {
    if [ "$QUIET" -eq 1 ]; then
        return 0
    fi
    printf '%s\n' "$*"
}

warn() {
    printf 'warning: %s\n' "$*" >&2
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

require_cmd() {
    command -v "$1" >/dev/null 2>&1 ||
        die "missing dependency '$1' (pacman -S $2)"
}

parse_args() {
    while [ "$#" -gt 0 ]; do
        case $1 in
        -a | --apps-root)
            [ "$#" -ge 2 ] || die "$1 needs a directory"
            APPS_ROOT=$2
            shift 2
            ;;
        -Q | --quadlet-dir)
            [ "$#" -ge 2 ] || die "$1 needs a directory"
            QUADLET_DIR=$2
            shift 2
            ;;
        -n | --dry-run)
            DRY_RUN=1
            shift
            ;;
        -q | --quiet)
            QUIET=1
            shift
            ;;
        --no-reload)
            RELOAD=0
            shift
            ;;
        --skip)
            [ "$#" -ge 2 ] || die "$1 needs an app name"
            SKIP_APPS="$SKIP_APPS$2 "
            shift 2
            ;;
        --clean)
            CLEAN=1
            shift
            ;;
        -h | --help)
            usage
            exit 0
            ;;
        --)
            shift
            break
            ;;
        -*)
            die "unknown option: $1 (see --help)"
            ;;
        *)
            [ -z "$HOST" ] || die "unexpected argument: $1"
            HOST=$1
            shift
            ;;
        esac
    done

    if [ "$#" -gt 0 ]; then
        [ -z "$HOST" ] || die "unexpected argument: $1"
        HOST=$1
    fi
}

resolve_paths() {
    HOST=${HOST:-$(uname -n)}
    HOST=${HOST%%.*}
    case $HOST in
    '' | [!A-Za-z0-9]* | *[!A-Za-z0-9._-]*) die "invalid host name: $HOST" ;;
    esac

    APPS_ROOT=$(abspath "$APPS_ROOT")
    HOST_DIR=$APPS_ROOT/$HOST
    QUADLET_DIR=$(abspath "$QUADLET_DIR")
    LINK=$QUADLET_DIR/apps-$HOST
}

quadlet_path_is_standard() {
    _qp_uid=$(id -u)
    for candidate in \
        "${XDG_CONFIG_HOME:-$HOME/.config}/containers/systemd" \
        "${XDG_RUNTIME_DIR:-/run/user/$_qp_uid}/containers/systemd" \
        "/etc/containers/systemd/users/$_qp_uid" \
        "/usr/share/containers/systemd/users/$_qp_uid"; do
        if [ "$QUADLET_DIR" = "$(abspath "$candidate")" ]; then
            return 0
        fi
    done
    return 1
}

is_skipped() {
    case $SKIP_APPS in
    *" $1 "*) return 0 ;;
    esac
    return 1
}

# Print the Quadlet unit files directly inside an app directory.
list_units() {
    find "$1" -maxdepth 1 -type f \
        \( -name '*.container' -o -name '*.volume' \
        -o -name '*.network' -o -name '*.pod' \
        -o -name '*.kube' -o -name '*.build' \
        -o -name '*.quadlets' \) -print | LC_ALL=C sort
}

is_generated_file() {
    [ -f "$1" ] || return 1
    first=
    IFS= read -r first <"$1" || true
    case $first in
    "$MARKER_PREFIX"*) return 0 ;;
    esac
    return 1
}

mark_generated() {
    tmp=$1.marker
    {
        printf '%s from %s; edits will be overwritten.\n' "$MARKER_PREFIX" "$2"
        cat -- "$1"
    } >"$tmp"
    mv -f -- "$tmp" "$1"
}

seen_app_for() {
    awk -F '	' -v n="$1" '$1 == n { print $2; exit }' "$SEEN_FILE"
}

generate_app() {
    ga_app_dir=$1
    ga_app=$2
    ga_compose=$3

    if [ ! -s "$ga_app_dir/$ga_compose" ]; then
        warn "$ga_app: empty ${ga_compose}; nothing to generate"
        return 1
    fi

    ga_tmp=$(mktemp -d "$ga_app_dir/.quadlet-gen.XXXXXX") ||
        die "$ga_app: cannot create temporary directory in $ga_app_dir"
    ga_merged=$ga_tmp/compose.yaml
    ga_source=$ga_app_dir/$ga_compose

    if ! (cd "$ga_app_dir" && podman-compose --no-ansi -f "$ga_compose" config >"$ga_merged"); then
        warn "$ga_app: podman-compose config failed"
        rm -rf -- "$ga_tmp"
        return 1
    fi

    if ! ga_out=$(podlet --skip-services-check --file "$ga_tmp" compose "$ga_merged" 2>&1); then
        ga_esc=$(printf '\033')
        printf '%s\n' "$ga_out" | sed "s/${ga_esc}\[[0-9;]*[mK]//g" >&2
        warn "$ga_app: podlet compose failed"
        rm -rf -- "$ga_tmp"
        return 1
    fi

    list_units "$ga_tmp" >"$ga_tmp/units"
    : >"$ga_tmp/fresh"
    : >"$ga_tmp/seen"
    ga_rc=0

    while IFS= read -r file; do
        name=${file##*/}

        seen_app=$(seen_app_for "$name")
        if [ -n "$seen_app" ]; then
            warn "$ga_app: unit '$name' already generated by '$seen_app'"
            ga_rc=1
            continue
        fi

        if [ -e "$ga_app_dir/$name" ] && ! is_generated_file "$ga_app_dir/$name"; then
            warn "$ga_app: refusing to overwrite $ga_app_dir/$name (not generated by this script)"
            ga_rc=1
            continue
        fi

        # A flat unit in the search path would collide with the generated one
        # even though both live in different directories.
        if [ -e "$QUADLET_DIR/$name" ]; then
            warn "$ga_app: $QUADLET_DIR/$name already exists; unit names would collide"
            ga_rc=1
            continue
        fi

        if [ ! -s "$file" ]; then
            warn "$ga_app: empty unit file generated: $name"
            ga_rc=1
            continue
        fi

        mark_generated "$file" "$ga_source"
        printf '%s\n' "$name" >>"$ga_tmp/fresh"
        printf '%s	%s\n' "$name" "$ga_app" >>"$ga_tmp/seen"
    done <"$ga_tmp/units"

    ga_count=$(wc -l <"$ga_tmp/fresh" | tr -d ' ')
    if [ "$ga_rc" -ne 0 ] || [ "$ga_count" -eq 0 ]; then
        [ "$ga_count" -eq 0 ] && warn "$ga_app: no Quadlet files generated"
        rm -rf -- "$ga_tmp"
        return 1
    fi

    if [ "$DRY_RUN" -eq 1 ]; then
        while IFS= read -r name; do
            log "would write $ga_app_dir/$name"
        done <"$ga_tmp/fresh"
        list_units "$ga_app_dir" >"$ga_tmp/old"
        while IFS= read -r file; do
            name=${file##*/}
            grep -Fqx "$name" "$ga_tmp/fresh" || log "would prune $file"
        done <"$ga_tmp/old"
        rm -rf -- "$ga_tmp"
        return 0
    fi

    while IFS= read -r name; do
        mv -f -- "$ga_tmp/$name" "$ga_app_dir/$name"
    done <"$ga_tmp/fresh"
    cat "$ga_tmp/seen" >>"$SEEN_FILE"

    list_units "$ga_app_dir" >"$ga_tmp/old"
    while IFS= read -r file; do
        name=${file##*/}
        if grep -Fqx "$name" "$ga_tmp/fresh"; then
            continue
        fi
        rm -f -- "$file"
        log "$ga_app: pruned $name"
    done <"$ga_tmp/old"

    names=$(tr '\n' ' ' <"$ga_tmp/fresh")
    log "$ga_app: ${names% }"
    rm -rf -- "$ga_tmp"
}

link_target_path() {
    [ -L "$1" ] || return 1
    raw=$(readlink -- "$1") || return 1
    [ -n "$raw" ] || return 1
    case $raw in
    /*) ;;
    *) raw="$(dirname -- "$1")/$raw" ;;
    esac
    abspath "$raw"
}

is_our_link() {
    [ -L "$1" ] || return 1
    _ol_target=$(link_target_path "$1") || return 1
    case $_ol_target in
    "$APPS_ROOT" | "$APPS_ROOT"/*) return 0 ;;
    esac
    return 1
}

prune_old_links() {
    [ -d "$QUADLET_DIR" ] || return 0
    host_target=$(abspath "$HOST_DIR")
    find "$QUADLET_DIR" -maxdepth 1 -type l \
        \( -name 'apps' -o -name 'apps-*' \) -print | LC_ALL=C sort >"$TMP_ROOT/links"
    while IFS= read -r link; do
        if [ "$link" = "$LINK" ]; then
            continue
        fi
        target=$(link_target_path "$link" || true)
        [ "$target" = "$host_target" ] || continue
        if [ "$DRY_RUN" -eq 1 ]; then
            log "would remove old link ${link} -> ${target}"
        else
            rm -f -- "$link"
            log "removed old link ${link} -> ${target}"
        fi
    done <"$TMP_ROOT/links"
}

ensure_link() {
    target=$(abspath "$HOST_DIR")
    if [ -L "$LINK" ]; then
        current=$(link_target_path "$LINK" || true)
        if [ "$current" = "$target" ]; then
            log "link ok: ${LINK} -> ${target}"
            return 0
        fi
        if is_our_link "$LINK"; then
            if [ "$DRY_RUN" -eq 1 ]; then
                log "would replace old link ${LINK} -> ${current}"
            else
                rm -f -- "$LINK"
                log "removed old link ${LINK} -> ${current}"
            fi
        else
            die "${LINK} points to ${current:-<broken>}, expected ${target}"
        fi
    fi
    if [ -e "$LINK" ]; then
        die "${LINK} exists and is not a symlink; refusing to replace it"
    fi

    if [ "$DRY_RUN" -eq 1 ]; then
        log "would link ${LINK} -> ${target}"
        return 0
    fi

    mkdir -p -- "$QUADLET_DIR"
    ln -s -- "$target" "$LINK"
    log "linked ${LINK} -> ${target}"
}

maybe_reload() {
    [ "$RELOAD" -eq 1 ] || return 0
    [ "$DRY_RUN" -eq 1 ] && return 0
    if ! command -v systemctl >/dev/null 2>&1; then
        warn "systemctl not found; run 'systemctl --user daemon-reload' manually"
        return 0
    fi
    if systemctl --user daemon-reload; then
        log "systemd user manager reloaded"
    else
        warn "systemctl --user daemon-reload failed; units are on disk"
        return 1
    fi
}

clean_generated() {
    count=0
    if [ -d "$HOST_DIR" ]; then
        find "$HOST_DIR" -mindepth 1 -maxdepth 1 -type d -print |
            LC_ALL=C sort >"$TMP_ROOT/appdirs"
        while IFS= read -r app_dir; do
            list_units "$app_dir" >"$TMP_ROOT/units"
            while IFS= read -r file; do
                is_generated_file "$file" || continue
                if [ "$DRY_RUN" -eq 1 ]; then
                    log "would remove ${file}"
                else
                    rm -f -- "$file"
                    log "removed ${file}"
                fi
                count=$((count + 1))
            done <"$TMP_ROOT/units"
        done <"$TMP_ROOT/appdirs"
    fi

    [ "$count" -eq 0 ] && log "no generated units found under ${HOST_DIR}"

    if [ -d "$QUADLET_DIR" ]; then
        host_target=$(abspath "$HOST_DIR")
        find "$QUADLET_DIR" -maxdepth 1 -type l \
            \( -name 'apps' -o -name 'apps-*' \) -print | LC_ALL=C sort >"$TMP_ROOT/links"
        while IFS= read -r link; do
            target=$(link_target_path "$link" || true)
            [ "$target" = "$host_target" ] || continue
            if [ "$DRY_RUN" -eq 1 ]; then
                log "would remove ${link} -> ${target}"
            else
                rm -f -- "$link"
                log "removed ${link} -> ${target}"
            fi
        done <"$TMP_ROOT/links"
    fi

    maybe_reload || true
}

main() {
    parse_args "$@"
    resolve_paths

    TMP_ROOT=$(mktemp -d "${TMPDIR:-/tmp}/gen-quadlets.XXXXXX")
    SEEN_FILE=$TMP_ROOT/seen
    : >"$SEEN_FILE"
    trap 'rm -rf -- "$TMP_ROOT"' 0

    if ! quadlet_path_is_standard; then
        warn "${QUADLET_DIR} is not in the rootless Quadlet search path"
        warn "the generator will not load units from there (see podman-systemd.unit(5))"
    fi

    if [ "$CLEAN" -eq 1 ]; then
        clean_generated
        return 0
    fi

    [ -d "$HOST_DIR" ] || die "no such host stack: ${HOST_DIR}"
    require_cmd podman-compose podman-compose
    require_cmd podlet podlet

    find "$HOST_DIR" -mindepth 2 -maxdepth 2 -type f \
        \( -name 'compose.yaml' -o -name 'compose.yml' \) -print |
        LC_ALL=C sort >"$TMP_ROOT/compose"
    [ -s "$TMP_ROOT/compose" ] ||
        die "no compose.yaml files found under ${HOST_DIR}"

    ok=0
    failed=0
    skipped=0
    reload_failed=0
    failed_apps=""

    while IFS= read -r compose; do
        app_dir=${compose%/*}
        app=${app_dir##*/}
        if is_skipped "$app"; then
            log "$app: skipped (--skip)"
            skipped=$((skipped + 1))
            continue
        fi
        if generate_app "$app_dir" "$app" "${compose##*/}"; then
            ok=$((ok + 1))
        else
            failed=$((failed + 1))
            failed_apps="$failed_apps $app"
        fi
    done <"$TMP_ROOT/compose"

    prune_old_links
    ensure_link
    maybe_reload || reload_failed=1

    printf '\ngenerated: %d app(s), skipped: %d, failed: %d\n' "$ok" "$skipped" "$failed"
    if [ -n "$failed_apps" ]; then
        printf 'failed apps:%s\n' "$failed_apps" >&2
    fi
    if [ "$failed" -ne 0 ] || [ "$reload_failed" -ne 0 ]; then
        return 1
    fi
    return 0
}

main "$@"
